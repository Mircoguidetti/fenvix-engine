#!/usr/bin/env python3
"""Review round 2: MCR2-<name>.cfg. Scenario configurations run the fixed spec's rules
(Ctl = "none") with one behaviour the model leaves out (Rv); -fix adds the remedy."""
BASE = dict(MaxSeq=1, MaxComp=2, MaxRuns=5, MaxVer=6, MaxCrash=0, MaxFork=0,
            Tpin=1, Lease=2, HoldLife=3, RemoteLease=4, Grace=4, Cap=4, UseFollower="FALSE",
            UseCkpt="FALSE", E0Start="FALSE", Lean="TRUE", CkLeaseLife=3, MaxRollback=0,
            CutOff="FALSE", Tout=1, ZL=0)
INV = ["TypeOK", "NoBadRead", "LatestReadOK", "CkptReadOK", "ForkReadOK",
       "EncodingOK", "XgOK", "ErasedGone"]
def cfg(name, rv, fix, over, readers, ctl="none", stop=0):
    p = dict(BASE); p.update(over)
    L = [f"\\* generated by gen_review_r2.py: {name}", "CONSTANTS", "  a1 = a1", "  a2 = a2", "  b1 = b1",
         "  Keys <- MCKeys", "  Groups <- MCGroups", "  Cust <- MCCust", "  Grp0 <- MCGrp0"]
    L += [f"  {k} = {v}" for k, v in p.items()]
    L += [f"  Readers = {{{readers}}}", f'  Ctl = "{ctl}"', f'  Rv = "{rv}"', f"  RvFix = {fix}",
          f"  StopAfter = {stop}", "SPECIFICATION SpecR", "SYMMETRY MCSym", "CONSTRAINT MCBudget", "INVARIANTS"]
    L += [f"  {i}" for i in INV] + ["CHECK_DEADLOCK FALSE", ""]
    open(f"MCR2-{name}.cfg", "w").write("\n".join(L))
# the review copy with Rv = "none" must match the owner's ZombieShortLease-ok (2,458,607 states)
cfg("none-ZombieShortLease-ok", "none", "FALSE", {"MaxCrash": 1, "CutOff": "TRUE"}, '"txn"')
# A. the PUT lands, its answer arrives later (before any timeout): remote drop and GC
ACK = {"Lean": "FALSE"}
cfg("AckDelay", "AckDelay", "FALSE", ACK, '"find"')                 # no bound on the answer
cfg("AckDelay-fix", "AckDelay", "TRUE", dict(ACK, Tout=1), '"find"', stop=900)  # hold life + timeout <= remote lease, grace
cfg("AckDelay-t2", "AckDelay", "TRUE", dict(ACK, Tout=2), '"find"')   # timeout too long for the margin
# B. the cut-off old waiter begins new holds after the takeover
ZB = {"MaxSeq": 2, "MaxCrash": 1, "CutOff": "TRUE", "ZL": 1}
cfg("ZombieBegin", "ZombieBegin", "FALSE", ZB, '"find"')
cfg("ZombieBegin-fix", "ZombieBegin", "TRUE", ZB, '"find"', stop=900)
