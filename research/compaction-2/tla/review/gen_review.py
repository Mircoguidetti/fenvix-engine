#!/usr/bin/env python3
"""Writes the review's TLC configurations: MCR-<scenario>.cfg (the delivered rules, Ctl = "none",
must FAIL) and MCR-<scenario>-fix.cfg (the same with the proposed remedy, must PASS)."""
BASE = dict(MaxSeq=1, MaxComp=2, MaxRuns=5, MaxVer=6, MaxCrash=0, MaxFork=0,
            Tpin=1, Lease=2, HoldLife=3, RemoteLease=4, Grace=4, Cap=4, UseFollower="FALSE",
            UseCkpt="FALSE", E0Start="FALSE", Lean="TRUE", CkLeaseLife=3)
INV = ["TypeOK", "NoBadRead", "LatestReadOK", "CkptReadOK", "ForkReadOK",
       "EncodingOK", "XgOK", "ErasedGone"]
SCEN = {  # scenario: (overrides, owner readers, groups map, symmetry)
    "StaleOwner":    ({"MaxCrash": 1}, '"find"', "MCGrp0", True),
    "ZombieHolds":   ({"MaxCrash": 1}, '"txn"', "MCGrp0", True),
    "FollowerEenv":  ({"UseFollower": "TRUE", "E0Start": "TRUE"}, '', "MCGrp0", True),
    "Rollback":      ({"E0Start": "TRUE"}, '', "MCGrp0", True),
    "SpanGroups":    ({"MaxSeq": 2}, '', "MCGrp0Span", False),
    "CkLeaseExpiry": ({"UseCkpt": "TRUE"}, '', "MCGrp0", True),
}
def cfg(name, rv, fix, over, readers, grp, sym, stop, inv=INV):
    p = dict(BASE); p.update(over)
    L = [f"\\* generated by gen_review.py: {name}", "CONSTANTS", "  a1 = a1", "  a2 = a2", "  b1 = b1",
         "  Keys <- MCKeys", "  Groups <- MCGroups", "  Cust <- MCCust", f"  Grp0 <- {grp}"]
    L += [f"  {k} = {v}" for k, v in p.items()]
    L += [f"  Readers = {{{readers}}}", '  Ctl = "none"', f'  Rv = "{rv}"', f"  RvFix = {fix}",
          f"  StopAfter = {stop}", "SPECIFICATION Spec"]
    if sym: L.append("SYMMETRY MCSym")
    L += ["CONSTRAINT MCBudget", "INVARIANTS"] + [f"  {i}" for i in inv] + ["CHECK_DEADLOCK FALSE", ""]
    open(f"MCR-{name}.cfg", "w").write("\n".join(L))
for s, (o, r, g, sym) in SCEN.items():
    cfg(s, s, "FALSE", o, r, g, sym, 0)
    if s != "FollowerEenv":
        cfg(s + "-fix", s, "TRUE", o, r, g, sym, 300)
# Rv = "none": the review copy must behave exactly as the delivered spec (same state count)
cfg("none-DropBeforePublish-ok", "none", "FALSE",
    dict(MaxSeq=1, MaxCrash=1, Lean="FALSE"), '', "MCGrp0", True, 0)
# Coverage: a hold across two drop jobs, with a newer version published meanwhile.
# The witness run must report WitnessTwoDrops "violated" (the state is reachable); the plain
# run is the correct model on the same configuration, run to completion.
COV = dict(MaxSeq=2, MaxComp=0, MaxCrash=0)
cfg("Cov-TwoDrops-witness", "Cov", "FALSE", COV, '"txn"', "MCGrp0", True, 0, INV + ["WitnessTwoDrops"])
cfg("Cov-TwoDrops", "none", "FALSE", COV, '"txn"', "MCGrp0", True, 0)
