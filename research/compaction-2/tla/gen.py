#!/usr/bin/env python3
"""Writes the TLC configurations: MC-main.cfg (the correct model) and MC-<control>.cfg."""
import sys
BASE = dict(MaxSeq=3, MaxComp=2, MaxRuns=5, MaxVer=6, MaxCrash=1, MaxFork=1,
            Tpin=1, Lease=2, HoldLife=3, RemoteLease=4, Grace=4, Cap=4, UseFollower="TRUE", UseCkpt="TRUE", E0Start="TRUE", Lean="FALSE",
            CkLeaseLife=3, MaxRollback=1, CutOff="TRUE")
INV = ["TypeOK", "NoBadRead", "LatestReadOK", "CkptReadOK", "ForkReadOK",
       "EncodingOK", "XgOK", "ErasedGone"]
CONTROLS = ["DropBeforePublish", "GcNoGrace", "ReadNoCut", "ResealSkip", "HoldsIgnored",
            "TxnRereads", "LeaseFromStamp", "FollowerCheckOnce", "RevokeNoCheck",
            "DropRemoteShortLease", "ForkCopyEenv", "CkptNoLease", "MergeConcat",
            "DeltaDropEnv", "FollowerNoTpin", "ForkNewestCut", "MergeAtMaxCut"]
def cfg(name, ctl, over=None, inv=None, readers='"find", "txn"', stop=0, grp="MCGrp0", sym=True):
    p = dict(BASE); p.update(over or {})
    lines = [f"\\* generated by gen.py: {name}", "CONSTANTS",
             "  a1 = a1", "  a2 = a2", "  b1 = b1", "  Keys <- MCKeys", "  Groups <- MCGroups", "  Cust <- MCCust", f"  Grp0 <- {grp}"]
    lines += [f"  {k} = {v}" for k, v in p.items()]
    lines += [f'  Readers = {{{readers}}}', f'  Ctl = "{ctl}"', f"  StopAfter = {stop}",
              "SPECIFICATION Spec"] + (["SYMMETRY MCSym"] if sym else []) + ["CONSTRAINT MCBudget", "INVARIANTS"]
    lines += [f"  {i}" for i in (inv or INV)]
    lines += ["CHECK_DEADLOCK FALSE", ""]
    open(f"MC-{name}.cfg", "w").write("\n".join(lines))
import os
cfg("main", "none", stop=int(os.environ.get("MAIN_STOP", "5400")))   # the full shape does not close
# Negative controls: each runs with only the parts its failure needs, so BFS reaches the
# (deep) violating trace in minutes; the parts left out are listed here.
SMALL = dict(MaxSeq=2, MaxComp=2, MaxCrash=1, MaxFork=0, UseFollower="FALSE", UseCkpt="FALSE",
             E0Start="FALSE", MaxRollback=0, CutOff="FALSE")
NEEDS = {  # control: (overrides on SMALL, owner readers)
    "DropBeforePublish":    ({"MaxSeq": 1}, ""),
    "GcNoGrace":            ({}, '"txn"'),
    "ReadNoCut":            ({"MaxSeq": 3, "MaxCrash": 0, "Lean": "TRUE"}, ""),
    "ResealSkip":           ({}, ""),
    "HoldsIgnored":         ({"MaxSeq": 1}, '"txn"'),
    "TxnRereads":           ({}, '"txn"'),
    "LeaseFromStamp":       ({"MaxSeq": 1, "UseFollower": "TRUE"}, ""),
    "FollowerCheckOnce":    ({"MaxSeq": 1, "UseFollower": "TRUE"}, ""),
    "RevokeNoCheck":        ({"MaxSeq": 1}, '"txn"'),
    "DropRemoteShortLease": ({"MaxSeq": 1}, '"txn"'),
    "ForkCopyEenv":         ({"MaxFork": 1, "UseCkpt": "TRUE", "E0Start": "TRUE"}, ""),
    "CkptNoLease":          ({"MaxSeq": 1, "UseCkpt": "TRUE"}, ""),
    "MergeConcat":          ({}, ""),
    "DeltaDropEnv":         ({}, ""),
    "FollowerNoTpin":       ({"MaxSeq": 1, "UseFollower": "TRUE"}, ""),
    "ForkNewestCut":        ({"MaxFork": 1, "UseCkpt": "TRUE"}, ""),
    "MergeAtMaxCut":        ({"MaxSeq": 3, "MaxComp": 3, "MaxVer": 7, "MaxCrash": 0, "Lean": "TRUE"}, ""),
}
for c in CONTROLS:
    over, rds = NEEDS[c]
    o = dict(SMALL); o.update(over)
    cfg(c, c, o, readers=rds)
    # the same configuration, correct model: must pass (the deep one gets a time budget)
    # CkptNoLease-ok closes (about 18 minutes on 4 cores), so it runs without a budget
    cfg(c + "-ok", "none", o, readers=rds, stop=1800 if c == "CkptNoLease" else 150)
# the group merge by concatenation, checked on reads only (without the structural XgOK):
# needs a third rewrite (a delta merge that removes the dead envelope)
cfg("MergeConcat-reads", "MergeConcat", dict(SMALL, MaxSeq=3, MaxComp=3, MaxVer=7, MaxCrash=0, Lean="TRUE"),
    [i for i in INV if i != "XgOK"], readers="")
cfg("MergeConcat-reads-ok", "none", dict(SMALL, MaxSeq=3, MaxComp=3, MaxVer=7, MaxCrash=0, Lean="TRUE"),
    [i for i in INV if i != "XgOK"], readers="", stop=150)

# The fix round (FIX 5): one control per review scenario, each the delivered rule without
# its remedy (must FAIL), and its twin with the remedy (must PASS, run to completion).
# The configurations are the reviewer's (research/compaction-2/tla/review/gen_review.py).
FIX = dict(MaxSeq=1, MaxComp=2, MaxCrash=0, MaxFork=0, UseFollower="FALSE", UseCkpt="FALSE",
           E0Start="FALSE", Lean="TRUE", MaxRollback=0, CutOff="FALSE")
FIXNEEDS = {  # name: (control, overrides on FIX, owner readers, groups map, symmetry)
    "NoFence-crash":    ("NoFence", {"MaxCrash": 1}, '"find"', "MCGrp0", True),           # F1
    "NoFence-timeout":  ("NoFence", {"Lean": "FALSE"}, '"find"', "MCGrp0", True),         # F1, no crash
    "FollowerOldEenv":  ("FollowerOldEenv", {"UseFollower": "TRUE", "E0Start": "TRUE"}, '', "MCGrp0", True),  # F2
    "E1NoWait":         ("E1NoWait", {"UseFollower": "TRUE", "E0Start": "TRUE"}, '', "MCGrp0", True),
    "FollowerNoMarker": ("FollowerNoMarker", {"UseFollower": "TRUE", "E0Start": "TRUE"}, '', "MCGrp0", True),
    "EraseOneGroup":    ("EraseOneGroup", {"MaxSeq": 2}, '', "MCGrp0Span", False),        # F3
    "CkNoRecheck":      ("CkNoRecheck", {"UseCkpt": "TRUE"}, '', "MCGrp0", True),         # F4
    "RollbackPlain":    ("RollbackPlain", {"E0Start": "TRUE", "MaxRollback": 1}, '', "MCGrp0", True),  # F5
    "ZombieShortLease": ("ZombieShortLease", {"MaxCrash": 1, "CutOff": "TRUE"}, '"txn"', "MCGrp0", True),  # N1
}
for n, (c, over, rds, grp, sym) in FIXNEEDS.items():
    o = dict(FIX); o.update(over)
    cfg(n, c, o, readers=rds, grp=grp, sym=sym)
    cfg(n + "-ok", "none", o, readers=rds, grp=grp, sym=sym, stop=900 if n == "NoFence-timeout" else 0)
# F3 with more of the system: customer A over two groups, with the readers and a crash
cfg("Span-ok", "none", dict(SMALL, MaxSeq=2), readers='"find", "txn"', grp="MCGrp0Span", sym=False, stop=1800)
