#!/usr/bin/env python3
"""Writes the TLC configurations: MC-main.cfg (the correct model) and MC-<control>.cfg."""
import sys
BASE = dict(MaxSeq=3, MaxComp=2, MaxRuns=5, MaxVer=6, MaxCrash=1, MaxFork=1,
            Tpin=1, Lease=2, HoldLife=3, RemoteLease=4, Grace=4, Cap=4, UseFollower="TRUE", UseCkpt="TRUE", E0Start="TRUE", Lean="FALSE")
INV = ["TypeOK", "NoBadRead", "LatestReadOK", "CkptReadOK", "ForkReadOK",
       "EncodingOK", "XgOK", "ErasedGone"]
CONTROLS = ["DropBeforePublish", "GcNoGrace", "ReadNoCut", "ResealSkip", "HoldsIgnored",
            "TxnRereads", "LeaseFromStamp", "FollowerCheckOnce", "RevokeNoCheck",
            "DropRemoteShortLease", "ForkCopyEenv", "CkptNoLease", "MergeConcat",
            "DeltaDropEnv", "FollowerNoTpin", "ForkNewestCut"]
def cfg(name, ctl, over=None, inv=None, readers='"find", "txn"', stop=0):
    p = dict(BASE); p.update(over or {})
    lines = [f"\\* generated by gen.py: {name}", "CONSTANTS",
             "  a1 = a1", "  a2 = a2", "  b1 = b1", "  Keys <- MCKeys", "  Groups <- MCGroups", "  Cust <- MCCust", "  Grp0 <- MCGrp0"]
    lines += [f"  {k} = {v}" for k, v in p.items()]
    lines += [f'  Readers = {{{readers}}}', f'  Ctl = "{ctl}"', f"  StopAfter = {stop}",
              "SPECIFICATION Spec", "SYMMETRY MCSym", "CONSTRAINT MCBudget", "INVARIANTS"]
    lines += [f"  {i}" for i in (inv or INV)]
    lines += ["CHECK_DEADLOCK FALSE", ""]
    open(f"MC-{name}.cfg", "w").write("\n".join(lines))
cfg("main", "none", stop=5400)   # the full shape does not close: 90 minutes on 4 cores
# Negative controls: each runs with only the parts its failure needs, so BFS reaches the
# (deep) violating trace in minutes; the parts left out are listed here.
SMALL = dict(MaxSeq=2, MaxComp=2, MaxCrash=1, MaxFork=0, UseFollower="FALSE", UseCkpt="FALSE",
             E0Start="FALSE")
NEEDS = {  # control: (overrides on SMALL, owner readers)
    "DropBeforePublish":    ({"MaxSeq": 1}, ""),
    "GcNoGrace":            ({}, '"txn"'),
    "ReadNoCut":            ({"MaxSeq": 3, "MaxCrash": 0, "Lean": "TRUE"}, ""),
    "ResealSkip":           ({}, ""),
    "HoldsIgnored":         ({"MaxSeq": 1}, '"txn"'),
    "TxnRereads":           ({}, '"txn"'),
    "LeaseFromStamp":       ({"MaxSeq": 1, "UseFollower": "TRUE"}, ""),
    "FollowerCheckOnce":    ({"MaxSeq": 1, "UseFollower": "TRUE"}, ""),
    "RevokeNoCheck":        ({"MaxSeq": 1}, '"txn"'),
    "DropRemoteShortLease": ({"MaxSeq": 1}, '"txn"'),
    "ForkCopyEenv":         ({"MaxFork": 1, "UseCkpt": "TRUE", "E0Start": "TRUE"}, ""),
    "CkptNoLease":          ({"MaxSeq": 1, "UseCkpt": "TRUE"}, ""),
    "MergeConcat":          ({}, ""),
    "DeltaDropEnv":         ({}, ""),
    "FollowerNoTpin":       ({"MaxSeq": 1, "UseFollower": "TRUE"}, ""),
    "ForkNewestCut":        ({"MaxFork": 1, "UseCkpt": "TRUE"}, ""),
}
for c in CONTROLS:
    over, rds = NEEDS[c]
    o = dict(SMALL); o.update(over)
    cfg(c, c, o, readers=rds)
    # the same configuration, correct model: must pass (the deep one gets a time budget)
    # CkptNoLease-ok closes (about 18 minutes on 4 cores), so it runs without a budget
    cfg(c + "-ok", "none", o, readers=rds, stop=0 if c == "CkptNoLease" else 300)
# the group merge by concatenation, checked on reads only (without the structural XgOK):
# needs a third rewrite (a delta merge that removes the dead envelope)
cfg("MergeConcat-reads", "MergeConcat", dict(SMALL, MaxSeq=3, MaxComp=3, MaxCrash=0, Lean="TRUE"),
    [i for i in INV if i != "XgOK"], readers="")
cfg("MergeConcat-reads-ok", "none", dict(SMALL, MaxSeq=3, MaxComp=3, MaxCrash=0, Lean="TRUE"),
    [i for i in INV if i != "XgOK"], readers="", stop=300)
