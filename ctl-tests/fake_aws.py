"""A fake EC2 instance metadata service (IMDSv2) and a fake S3, both in memory on 127.0.0.1, for the credential-renewal test
(test_19). No AWS, no real credentials: every key, secret and token here is generated by this file and only means something to it.

* FakeImds: PUT /latest/api/token gives a session token; GET /latest/meta-data/iam/security-credentials/ (only with that token,
  as with IMDSv2 required) gives the role name; GET .../<role> gives NEW credentials at every request (AccessKeyId FAKEKEY0001,
  FAKEKEY0002, ...) that expire `ttl` seconds after they are issued (or, with `rotate_after`, the same credentials until they
  are that old, as on EC2). Each issued credential is registered in `Registry`.
* FakeS3: path-style S3 with the calls the engine makes (PUT with If-None-Match / If-Match, GET with Range, HEAD, DELETE,
  ListObjectsV2, multi-object delete, copy, multipart). Every request is checked like S3 does: the Access Key ID must be one the
  registry knows, it must not be expired at the time of the request (403 ExpiredToken), x-amz-security-token must be that key's
  token, and the SigV4 signature must match that key's secret (403 SignatureDoesNotMatch). Every request is logged with its time
  and Access Key ID, accepted or not."""
import base64
import hashlib
import hmac
import json
import re
import threading
import time
import urllib.parse
from datetime import datetime, timezone
from email.utils import formatdate
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from xml.sax.saxutils import escape


class Registry:
    """Credentials known to the fake AWS: key id -> {secret, token, issued, expires} (epoch seconds)."""

    def __init__(self):
        self.lock = threading.Lock()
        self.creds = {}

    def add(self, key, secret, token, issued, expires):
        with self.lock:
            self.creds[key] = {"secret": secret, "token": token, "issued": issued, "expires": expires}

    def get(self, key):
        with self.lock:
            return self.creds.get(key)


def _iso(t):
    return datetime.fromtimestamp(t, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


class _Server(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True


def _serve(handler_cls, owner):
    srv = _Server(("127.0.0.1", 0), handler_cls)
    srv.owner = owner
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv


class FakeImds:
    ROLE = "fake-engine-role"

    def __init__(self, registry, ttl, rotate_after=None):
        # rotate_after=None: new credentials at every request. A number: the same credentials are returned until they are that
        # many seconds old (as EC2 does: the role's credentials change only when AWS rotates them).
        self.registry, self.ttl, self.rotate_after = registry, ttl, rotate_after
        self.current = None
        self.down = False      # True: every metadata request gets 503 (an IMDS outage)
        self.lock = threading.Lock()
        self.n = 0
        self.tokens = set()
        self.log = []          # (time, method, path, ok)
        self.issued = []       # (time, key id, expires)
        self.srv = _serve(_ImdsHandler, self)
        self.url = f"http://127.0.0.1:{self.srv.server_address[1]}"

    def issue(self):
        if self.rotate_after is not None:
            with self.lock:
                cur = self.current
            if cur is not None and time.time() - cur[0] < self.rotate_after:
                return cur[1]
        with self.lock:
            self.n += 1
            n = self.n
        now = time.time()
        key = f"FAKEKEY{n:04d}"
        secret, token = f"fake-secret-{n:04d}-" + "x" * 20, f"fake-session-token-{n:04d}"
        # Expiration has second precision, as in IMDS: round down, so the key is never valid longer than `ttl`.
        expires = int(now + self.ttl)
        self.registry.add(key, secret, token, now, expires)
        doc = {"Code": "Success", "LastUpdated": _iso(now), "Type": "AWS-HMAC", "AccessKeyId": key,
               "SecretAccessKey": secret, "Token": token, "Expiration": _iso(expires)}
        with self.lock:
            self.issued.append((now, key, expires))
            self.current = (now, doc)
        return doc

    def close(self):
        self.srv.shutdown()
        self.srv.server_close()


class _ImdsHandler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, *a):
        pass

    def _send(self, code, body=b"", ctype="text/plain"):
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _drain(self):
        n = int(self.headers.get("Content-Length") or 0)
        if n:
            self.rfile.read(n)

    def do_PUT(self):
        o = self.server.owner
        self._drain()
        if o.down:
            o.log.append((time.time(), "PUT", self.path, None))
            return self._send(503)
        ok = self.path == "/latest/api/token" and self.headers.get("X-aws-ec2-metadata-token-ttl-seconds")
        o.log.append((time.time(), "PUT", self.path, bool(ok)))
        if not ok:
            return self._send(400)
        tok = "imds-session-" + hashlib.sha256(str(time.time()).encode()).hexdigest()[:16]
        with o.lock:
            o.tokens.add(tok)
        self._send(200, tok.encode())

    def do_GET(self):
        o = self.server.owner
        if o.down:
            o.log.append((time.time(), "GET", self.path, None))
            return self._send(503)
        tok = self.headers.get("X-aws-ec2-metadata-token")
        ok = tok in o.tokens
        o.log.append((time.time(), "GET", self.path, ok))
        if not ok:                      # IMDSv2 required: no token, no metadata
            return self._send(401)
        base = "/latest/meta-data/iam/security-credentials/"
        if self.path == base:
            return self._send(200, FakeImds.ROLE.encode())
        if self.path == base + FakeImds.ROLE:
            return self._send(200, json.dumps(o.issue()).encode(), "application/json")
        self._send(404)


def _q(s):
    return urllib.parse.quote(s, safe="-_.~")


class FakeS3:
    def __init__(self, registry, region="us-east-1"):
        self.registry, self.region = registry, region
        self.lock = threading.RLock()
        self.objects = {}      # (bucket, key) -> (bytes, etag, mtime)
        self.uploads = {}      # upload id -> {bucket, key, parts}
        self.log = []          # dicts: t, method, path, key_id, status, reason
        self.unsupported = []
        self.srv = _serve(_S3Handler, self)
        self.url = f"http://127.0.0.1:{self.srv.server_address[1]}"

    def close(self):
        self.srv.shutdown()
        self.srv.server_close()

    # ---- authentication, as S3 checks it
    def check(self, h):
        auth = h.headers.get("Authorization", "")
        m = re.match(r"AWS4-HMAC-SHA256 Credential=([^/]+)/(\d{8})/([^/]+)/s3/aws4_request, ?SignedHeaders=([^,]+), ?Signature=([0-9a-f]+)$", auth)
        if not m:
            return None, 403, "AccessDenied", "no SigV4 Authorization header"
        key, day, region, signed, sig = m.groups()
        c = self.registry.get(key)
        if c is None:
            return key, 403, "InvalidAccessKeyId", "unknown access key"
        if time.time() >= c["expires"]:
            return key, 403, "ExpiredToken", "The provided token has expired."
        if c["token"] is not None and h.headers.get("x-amz-security-token") != c["token"]:
            return key, 403, "InvalidToken", "security token does not belong to this key"
        raw_path, _, query = h.path.partition("?")
        pairs = sorted((_q(k), _q(v)) for k, v in urllib.parse.parse_qsl(query, keep_blank_values=True))
        cq = "&".join(f"{k}={v}" for k, v in pairs)
        names = signed.split(";")
        ch = "".join(f"{n}:{' '.join((h.headers.get(n) or '').split())}\n" for n in names)
        creq = "\n".join([h.command, raw_path, cq, ch, signed, h.headers.get("x-amz-content-sha256", "")])
        amz_date = h.headers.get("x-amz-date", "")
        sts = "\n".join(["AWS4-HMAC-SHA256", amz_date, f"{day}/{region}/s3/aws4_request", hashlib.sha256(creq.encode()).hexdigest()])
        k = ("AWS4" + c["secret"]).encode()
        for part in (day, region, "s3", "aws4_request"):
            k = hmac.new(k, part.encode(), hashlib.sha256).digest()
        if not hmac.compare_digest(hmac.new(k, sts.encode(), hashlib.sha256).hexdigest(), sig):
            return key, 403, "SignatureDoesNotMatch", "signature does not match"
        return key, None, None, None


class _S3Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, *a):
        pass

    def _send(self, code, body=b"", headers=(), ctype="application/xml"):
        self.send_response(code)
        if body or code not in (204, 304):
            self.send_header("Content-Type", ctype)
        for k, v in headers:
            self.send_header(k, v)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def _err(self, code, name, msg):
        body = f"<?xml version=\"1.0\" encoding=\"UTF-8\"?><Error><Code>{name}</Code><Message>{escape(msg)}</Message></Error>".encode()
        self._send(code, body)

    def _handle(self):
        o = self.server.owner
        n = int(self.headers.get("Content-Length") or 0)
        body = self.rfile.read(n) if n else b""
        key_id, code, name, msg = o.check(self)
        entry = {"t": time.time(), "method": self.command, "path": self.path.split("?")[0], "key_id": key_id,
                 "status": code or 200, "reason": name}
        o.log.append(entry)
        if code:
            return self._err(code, name, msg)
        try:
            st = self._op(o, body)
        except Exception as e:  # a bug here must show up in the test, not hang the engine
            o.unsupported.append(f"{self.command} {self.path}: {e!r}")
            st = 500
            self._err(500, "InternalError", repr(e))
        entry["status"] = st

    do_GET = do_PUT = do_HEAD = do_DELETE = do_POST = _handle

    # ---- S3 operations, path style: /<bucket>/<key>
    def _op(self, o, body):
        raw_path, _, query = self.path.partition("?")
        q = dict(urllib.parse.parse_qsl(query, keep_blank_values=True))
        parts = urllib.parse.unquote(raw_path).lstrip("/").split("/", 1)
        bucket, key = parts[0], (parts[1] if len(parts) > 1 else "")
        m = self.command
        with o.lock:
            if not key:
                if m == "GET" and q.get("list-type") == "2":
                    return self._list(o, bucket, q)
                if m == "POST" and "delete" in q:
                    return self._multi_delete(o, bucket, body)
                if m in ("HEAD", "PUT"):
                    self._send(200)
                    return 200
            else:
                obj = o.objects.get((bucket, key))
                if m == "POST" and "uploads" in q:
                    uid = hashlib.md5(f"{bucket}/{key}/{time.time()}".encode()).hexdigest()
                    o.uploads[uid] = {"bucket": bucket, "key": key, "parts": {}}
                    xml = f"<InitiateMultipartUploadResult><Bucket>{escape(bucket)}</Bucket><Key>{escape(key)}</Key><UploadId>{uid}</UploadId></InitiateMultipartUploadResult>"
                    self._send(200, xml.encode())
                    return 200
                if m == "PUT" and "uploadId" in q:
                    up = o.uploads.get(q["uploadId"])
                    if up is None:
                        self._err(404, "NoSuchUpload", "no such upload")
                        return 404
                    etag = '"%s"' % hashlib.md5(body).hexdigest()
                    up["parts"][int(q["partNumber"])] = body
                    self._send(200, headers=[("ETag", etag)])
                    return 200
                if m == "POST" and "uploadId" in q:
                    up = o.uploads.pop(q["uploadId"], None)
                    if up is None:
                        self._err(404, "NoSuchUpload", "no such upload")
                        return 404
                    data = b"".join(up["parts"][i] for i in sorted(up["parts"]))
                    if self.headers.get("If-None-Match") == "*" and obj is not None:
                        self._err(412, "PreconditionFailed", "exists")
                        return 412
                    etag = self._store(o, bucket, key, data)
                    xml = f"<CompleteMultipartUploadResult><Bucket>{escape(bucket)}</Bucket><Key>{escape(key)}</Key><ETag>{escape(etag)}</ETag></CompleteMultipartUploadResult>"
                    self._send(200, xml.encode())
                    return 200
                if m == "DELETE" and "uploadId" in q:
                    o.uploads.pop(q["uploadId"], None)
                    self._send(204)
                    return 204
                if m == "PUT":
                    inm, im = self.headers.get("If-None-Match"), self.headers.get("If-Match")
                    if inm == "*" and obj is not None:
                        self._err(412, "PreconditionFailed", "At least one of the pre-conditions you specified did not hold")
                        return 412
                    if im is not None:
                        if obj is None:
                            self._err(404, "NoSuchKey", "The specified key does not exist.")
                            return 404
                        if im != obj[1]:
                            self._err(412, "PreconditionFailed", "At least one of the pre-conditions you specified did not hold")
                            return 412
                    src = self.headers.get("x-amz-copy-source")
                    if src:
                        sb, _, sk = urllib.parse.unquote(src).lstrip("/").partition("/")
                        s = o.objects.get((sb, sk))
                        if s is None:
                            self._err(404, "NoSuchKey", "The specified key does not exist.")
                            return 404
                        etag = self._store(o, bucket, key, s[0])
                        xml = f"<CopyObjectResult><ETag>{escape(etag)}</ETag><LastModified>{_iso(time.time())}</LastModified></CopyObjectResult>"
                        self._send(200, xml.encode())
                        return 200
                    etag = self._store(o, bucket, key, body)
                    self._send(200, headers=[("ETag", etag)])
                    return 200
                if m in ("GET", "HEAD"):
                    if obj is None:
                        self._err(404, "NoSuchKey", "The specified key does not exist.")
                        return 404
                    data, etag, mtime = obj
                    im, inm = self.headers.get("If-Match"), self.headers.get("If-None-Match")
                    if im is not None and im != etag:
                        self._err(412, "PreconditionFailed", "If-Match")
                        return 412
                    if inm is not None and inm == etag:
                        self._send(304, headers=[("ETag", etag)])
                        return 304
                    hdr = [("ETag", etag), ("Last-Modified", formatdate(mtime, usegmt=True)), ("Accept-Ranges", "bytes")]
                    rng = self.headers.get("Range")
                    if rng and m == "GET":
                        a, b = self._range(rng, len(data))
                        if a is None:
                            self._err(416, "InvalidRange", "range")
                            return 416
                        hdr.append(("Content-Range", f"bytes {a}-{b - 1}/{len(data)}"))
                        self._send(206, data[a:b], hdr, "application/octet-stream")
                        return 206
                    if m == "HEAD":
                        self.send_response(200)
                        for k, v in hdr:
                            self.send_header(k, v)
                        self.send_header("Content-Length", str(len(data)))
                        self.end_headers()
                        return 200
                    self._send(200, data, hdr, "application/octet-stream")
                    return 200
                if m == "DELETE":
                    o.objects.pop((bucket, key), None)
                    self._send(204)
                    return 204
        o.unsupported.append(f"{m} {self.path}")
        self._err(501, "NotImplemented", "not implemented by the fake S3")
        return 501

    @staticmethod
    def _range(rng, size):
        mm = re.match(r"bytes=(\d*)-(\d*)$", rng.strip())
        if not mm:
            return None, None
        a, b = mm.groups()
        if a == "":
            a, b = max(0, size - int(b)), size
        else:
            a, b = int(a), (int(b) + 1 if b else size)
        b = min(b, size)
        if a >= size and size > 0:
            return None, None
        return a, b

    @staticmethod
    def _store(o, bucket, key, data):
        etag = '"%s"' % hashlib.md5(data + str(time.time_ns()).encode()).hexdigest()
        o.objects[(bucket, key)] = (data, etag, time.time())
        return etag

    def _list(self, o, bucket, q):
        prefix, delim = q.get("prefix", ""), q.get("delimiter", "")
        start = q.get("continuation-token") or q.get("start-after") or ""
        if q.get("continuation-token"):
            start = base64.urlsafe_b64decode(start.encode()).decode()
        maxk = int(q.get("max-keys", "1000"))
        keys = sorted(k for (b, k) in o.objects if b == bucket and k.startswith(prefix) and k > start)
        contents, prefixes, seen, last, trunc = [], [], set(), None, False
        for k in keys:
            if delim:
                rest = k[len(prefix):]
                if delim in rest:
                    cp = prefix + rest.split(delim, 1)[0] + delim
                    if cp not in seen:
                        if len(contents) + len(prefixes) >= maxk:
                            trunc = True
                            break
                        seen.add(cp)
                        prefixes.append(cp)
                    last = k
                    continue
            if len(contents) + len(prefixes) >= maxk:
                trunc = True
                break
            contents.append(k)
            last = k
        x = [f"<ListBucketResult><Name>{escape(bucket)}</Name><Prefix>{escape(prefix)}</Prefix><KeyCount>{len(contents) + len(prefixes)}</KeyCount>"
             f"<MaxKeys>{maxk}</MaxKeys><IsTruncated>{'true' if trunc else 'false'}</IsTruncated>"]
        if trunc:
            x.append(f"<NextContinuationToken>{base64.urlsafe_b64encode(last.encode()).decode()}</NextContinuationToken>")
        for k in contents:
            data, etag, mtime = o.objects[(bucket, k)]
            x.append(f"<Contents><Key>{escape(k)}</Key><LastModified>{datetime.fromtimestamp(mtime, timezone.utc).strftime('%Y-%m-%dT%H:%M:%S.000Z')}</LastModified>"
                     f"<ETag>{escape(etag)}</ETag><Size>{len(data)}</Size><StorageClass>STANDARD</StorageClass></Contents>")
        for p in prefixes:
            x.append(f"<CommonPrefixes><Prefix>{escape(p)}</Prefix></CommonPrefixes>")
        x.append("</ListBucketResult>")
        self._send(200, "".join(x).encode())
        return 200

    def _multi_delete(self, o, bucket, body):
        keys = re.findall(r"<Key>(.*?)</Key>", body.decode())
        out = []
        for k in keys:
            k = k.replace("&lt;", "<").replace("&gt;", ">").replace("&quot;", '"').replace("&apos;", "'").replace("&amp;", "&")
            o.objects.pop((bucket, k), None)
            out.append(f"<Deleted><Key>{escape(k)}</Key></Deleted>")
        self._send(200, ("<DeleteResult>" + "".join(out) + "</DeleteResult>").encode())
        return 200
